// Generates 08_Bestiary/regional_ecology.md from Data/ (species habitats, regions, region graph, population).
// Run: node Tools/monster_gen/region_ecology.js [--check]   (--check exits 1 if the file is stale)
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..', '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));

const species = read('Data/Monsters/species.json');
const regions = read('Data/World/regions.json');
const graph = read('Data/World/region_graph.json');
const pop = read('Data/Monsters/population.json');

const RANKS = ['F-', 'F', 'F+', 'E-', 'E', 'E+', 'D-', 'D', 'D+', 'C-', 'C', 'C+', 'B-', 'B', 'B+', 'A-', 'A', 'A+', 'S-', 'S', 'S+', 'SS', 'SSS'];
const rv = (r) => { const i = RANKS.indexOf(r); return i < 0 ? 99 : i; };

const byRegion = {};
for (const r of regions) byRegion[r.id] = [];
const orphans = [];
for (const s of species) {
  const hs = s.habitats || [];
  if (!hs.length) orphans.push(s);
  for (const h of hs) (byRegion[h] || (byRegion[h] = [])).push(s);
}
const popCount = {};
for (const p of pop) popCount[p.regionId] = (popCount[p.regionId] || 0) + 1;
const name = Object.fromEntries(regions.map((r) => [r.id, r.name]));
const speciesById = Object.fromEntries(species.map((s) => [s.id, s]));

const nbr = {};
for (const e of graph.edges) {
  (nbr[e.a] = nbr[e.a] || []).push(`${name[e.b] || e.b} (${e.kind})`);
  (nbr[e.b] = nbr[e.b] || []).push(`${name[e.a] || e.a} (${e.kind})`);
}

const out = [];
out.push('# Regional ecology');
out.push('');
out.push('Generated by `node Tools/monster_gen/region_ecology.js` from `Data/Monsters/species.json` (habitats), `Data/World/regions.json`, `Data/World/region_graph.json` and `Data/Monsters/population.json`. Do not edit by hand; edit the data and rerun. Prose ecology for the great regions lives in `10_World/gazetteer.md`.');
out.push('');
out.push(`${species.length} species, ${regions.length} regions, ${pop.length} population entries.`);
out.push('');
out.push('## Findings');
const over = [];
for (const r of regions) {
  for (const s of byRegion[r.id] || []) {
    if (rv(s.rank) > rv(r.rankMax) && !s.isTyrant) over.push(`${s.name} (${s.rank}) in ${r.name} (band ${r.rankMin}-${r.rankMax})`);
  }
}
out.push(`- Species with no habitat: ${orphans.length}${orphans.length ? ' (' + orphans.slice(0, 15).map((s) => s.name).join(', ') + (orphans.length > 15 ? ', ...' : '') + ')' : ''}.`);
out.push(`- Species above their region's top rank (tyrants excluded): ${over.length}${over.length ? ' (first 15: ' + over.slice(0, 15).join('; ') + ')' : ''}.`);
const empty = regions.filter((r) => !(byRegion[r.id] || []).length).map((r) => r.name);
out.push(`- Regions with no resident species: ${empty.length}${empty.length ? ' (' + empty.join(', ') + ')' : ''}.`);
const thin = regions.filter((r) => (byRegion[r.id] || []).length && (byRegion[r.id] || []).length < 10).map((r) => `${r.name} ${byRegion[r.id].length}`);
out.push(`- Regions with fewer than 10 species: ${thin.length}${thin.length ? ' (' + thin.join(', ') + ')' : ''}.`);
out.push('');
out.push('## Overview');
out.push('');
out.push('| Region | Ring | Band | Species | Population | Tyrant | Dominant families |');
out.push('|---|---|---|---|---|---|---|');
const fam = (list) => {
  const c = {};
  for (const s of list) c[s.family] = (c[s.family] || 0) + 1;
  return Object.entries(c).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 3).map(([f, n]) => `${f} ${n}`).join(', ');
};
for (const r of regions) {
  const list = byRegion[r.id] || [];
  const t = r.tyrantSpeciesId && speciesById[r.tyrantSpeciesId] ? speciesById[r.tyrantSpeciesId].name : (r.tyrantSpeciesId || '-');
  out.push(`| ${r.name} | ${r.ring} | ${r.rankMin}-${r.rankMax} | ${list.length} | ${popCount[r.id] || 0} | ${t} | ${fam(list) || '-'} |`);
}
out.push('');
out.push('## Per region');
for (const r of regions) {
  const list = (byRegion[r.id] || []).slice().sort((a, b) => rv(b.rank) - rv(a.rank) || a.name.localeCompare(b.name));
  out.push('');
  out.push(`### ${r.name} (\`${r.id}\`)`);
  out.push(`Ring ${r.ring}, ${r.layer}, ranks ${r.rankMin}-${r.rankMax}, biomes: ${(r.biomes || []).join(', ')}. Siege faction: ${r.siegeFaction || '-'}.`);
  const n = [...new Set(nbr[r.id] || [])];
  out.push(`Connected to: ${n.length ? n.join(', ') : 'none by road, pass, sea or border'}.`);
  out.push(`${list.length} resident species. Top: ${list.slice(0, 6).map((s) => `${s.name} (${s.rank})`).join(', ') || '-'}. Bottom: ${list.slice(-4).reverse().map((s) => `${s.name} (${s.rank})`).join(', ') || '-'}.`);
  out.push(`Families: ${fam(list) || '-'}.`);
}
out.push('');
const text = out.join('\n');
const target = path.join(root, '08_Bestiary', 'regional_ecology.md');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== text) { console.error('regional_ecology.md is stale: run node Tools/monster_gen/region_ecology.js'); process.exit(1); }
  console.log('regional_ecology.md is up to date');
} else {
  fs.writeFileSync(target, text);
  console.log('wrote', target, text.length, 'chars');
}
