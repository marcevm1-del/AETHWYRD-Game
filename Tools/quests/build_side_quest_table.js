// Writes 11_Quests_Encounters/side_quests/all_side_quests.md: one table of every side quest, built from the
// hidden <!-- quest --> blocks in the region and pattern docs. Run after editing a quest:
//   node Tools/quests/build_side_quest_table.js
'use strict';
const fs = require('fs');
const path = require('path');
const DIR = path.resolve(__dirname, '..', '..', '11_Quests_Encounters', 'side_quests');
const rows = []; const byRank = {}; const byType = {};
for (const f of fs.readdirSync(DIR).filter(f => /^\d\d_.*\.md$/.test(f)).sort()) {
  const text = fs.readFileSync(path.join(DIR, f), 'utf8');
  const title = (/^# (.+)$/m.exec(text) || [, f])[1].replace(/^11e-\d+ — /, '').replace(/ \(draft\)$/, '');
  const re = /<!-- quest\s*\n([\s\S]*?)-->/g; let m;
  while ((m = re.exec(text))) {
    const b = {}; for (const l of m[1].split('\n')) { const k = /^([a-z_]+):\s*(.*)$/.exec(l); if (k && !/^\s/.test(l)) b[k[1]] = k[2]; }
    rows.push({ f, title, b });
    byRank[b.rank] = (byRank[b.rank] || 0) + 1; byType[b.type] = (byType[b.type] || 0) + 1;
  }
}
const nice = s => s.replace(/^npc_/, '').replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
const reg = s => nice(s.replace(/^reg_/, 'npc_'));
let out = '# 11e — All Side Quests (generated)\n\n> Generated by `Tools/quests/build_side_quest_table.js` from the hidden data blocks in this folder. Do not edit by hand.\n\n';
out += `**Total:** ${rows.length} quests.  \n**By rank:** ${['F', 'E', 'D', 'C', 'B', 'A', 'S'].filter(r => byRank[r]).map(r => `${r} ${byRank[r]}`).join(' · ')}.  \n`;
out += `**By type:** ${Object.entries(byType).sort((a, b) => b[1] - a[1]).map(([t, c]) => `${t} ${c}`).join(' · ')}.\n\n`;
let cur = '';
for (const r of rows) {
  if (r.f !== cur) { cur = r.f; out += `\n## [${r.title}](${r.f})\n\n| Quest | Rank | Type | Region | Giver | Level |\n|---|---|---|---|---|---|\n`; }
  out += `| ${r.b.title} | ${r.b.rank} | ${r.b.type} | ${reg(r.b.region)} | ${nice(r.b.giver)} | ${r.b.level} |\n`;
}
fs.writeFileSync(path.join(DIR, 'all_side_quests.md'), out);
console.log(`Side-quest table: ${rows.length} quests`);
